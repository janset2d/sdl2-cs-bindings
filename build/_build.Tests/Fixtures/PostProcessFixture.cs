using System.Text.Json;
using Build.Host.Paths;
using Build.Targets.GenerateBindings.PostProcess;
using Build.Targets.GenerateBindings.PostProcess.Config;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using NSubstitute;

namespace Build.Tests.Fixtures;

internal static class PostProcessFixture
{
    public static string[] Lines(string name)
    {
        using var data = JsonDocument.Parse(FixtureLoader.Load("PostProcess/self-tests.json"));
        return [.. data.RootElement.GetProperty(name).EnumerateArray().Select(line => line.GetString()!)];
    }

    public static string Source(string name) => string.Join('\n', Lines(name));

    public static string Rewrite(string source, CSharpSyntaxRewriter rewriter)
    {
        var root = CSharpSyntaxTree.ParseText(source, CSharpParseOptions.Default).GetCompilationUnitRoot();
        return rewriter.Visit(root).ToFullString();
    }

    public static FakeCakeWorld World()
    {
        return FakeCakeWorld.CreateWindows()
            .WithTextFile("spikes/binding-generators/clangsharp/config/family-config.json", FixtureLoader.Load("PostProcess/family-config.json"));
    }

    public static Task<FamilyConfig> ConfigAsync(FakeCakeWorld world)
    {
        var paths = Substitute.For<IPathService>();
        paths.RepoRoot.Returns(world.RepoRoot);
        return FamilyConfig.LoadAsync(world.CakeContext, paths);
    }

    public static string Project(string source, string publicClass = "SDL", string rawClass = "SDLNative", string namespaceName = "SDL2")
    {
        return PublicTypedMethodProjection.BuildPublicClassContent(
            PublicTypedMethodProjection.DiscoverFromSource(source, rawClass), publicClass, rawClass, namespaceName,
            new HashSet<string>(["TTF_FontFaces", "SDL_ThreadID", "TTF_OpenFontIndex"], StringComparer.Ordinal));
    }

    public static string[] CompilationErrors(string source, bool modern)
    {
        string[] symbols = modern ? ["NET6_0_OR_GREATER", "NET5_0_OR_GREATER"] : [];
        var options = CSharpParseOptions.Default
            .WithLanguageVersion(LanguageVersion.Preview)
            .WithPreprocessorSymbols(symbols);
        var trees = source
            .Split(["// <auto-generated-split />", "// <auto-generated />"], StringSplitOptions.None)
            .Where(part => !string.IsNullOrWhiteSpace(part))
            .Select(part => CSharpSyntaxTree.ParseText(part, options));
        var references = AppDomain.CurrentDomain
            .GetAssemblies()
            .Where(assembly => !assembly.IsDynamic && !string.IsNullOrEmpty(assembly.Location))
            .Select(assembly => MetadataReference.CreateFromFile(assembly.Location));
        return [.. CSharpCompilation
            .Create("PublicProjectionTest", trees, references,
                new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true))
            .GetDiagnostics()
            .Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
            .Select(diagnostic => diagnostic.ToString())];
    }
}
