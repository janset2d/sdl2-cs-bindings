namespace Build.Tests.Fixtures.CodeStyle;

internal static class BlankLineBeforeBlockData
{
    private const string Prefix = """
        public static unsafe class Sample
        {
            public static void Run(object gate, int[] items)
            {
                var value = 1;
        """ + "\n        ";

    private const string Suffix = "\n    }\n}";

    public static IEnumerable<(string Source, string Expected)> Blocks()
    {
        string[] statements =
        [
            "if (value > 0) { }",
            "for (var index = 0; index < value; index++) { }",
            "foreach (var item in items) { }",
            "foreach (var (left, right) in new (int, int)[] { (1, 2) }) { }",
            "while (value > 0) { break; }",
            "do { value--; } while (value > 0);",
            "switch (value) { case 1: break; }",
