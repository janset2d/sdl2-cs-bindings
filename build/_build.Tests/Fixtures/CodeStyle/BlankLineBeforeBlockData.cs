            "using (var stream = new System.IO.MemoryStream()) { }",
            "lock (gate) { }",
            "fixed (int* pointer = items) { }"
        ];

        foreach (var statement in statements)
        {
            yield return (Prefix + statement + Suffix,
                string.Create(CultureInfo.InvariantCulture, $"JNS0002|{Prefix.Length}|Add a blank line before a block statement"));
        }
    }

