using Build.Data.BindingGeneration;
using Build.Data.BindingGeneration.Models;
using Build.Tests.Fixtures;

namespace Build.Tests.Unit.Data.BindingGeneration;

public sealed class DynapiManifestRepositoryTests
{
    private const string _samplePath = "/workspace/external/vcpkg/buildtrees/sdl2/src/se-2.32.10-3b143ac573.clean/src/dynapi/SDL2.exports";

    private static readonly string[] ThreeSymbolsExpected = ["SDL_Init", "SDL_Quit", "SDL_GetError"];
    private static readonly string[] OneSymbolExpected = ["SDL_Init"];

    [Test]
    public async Task LoadAsync_Should_Return_Manifest_When_Exactly_One_File_Matches()
    {
        var world = FakeCakeWorld.CreateLinux().WithTextFile(
            "external/vcpkg/buildtrees/sdl2/src/one/src/dynapi/SDL2.exports",
            "++'_SDL_Quit'.'SDL2.dll'.'SDL_Quit'\n++'_SDL_Init'.'SDL2.dll'.'SDL_Init'");
        var repository = new DynapiManifestRepository(world.CakeContext, world.CreateBuildContext().Paths);
        var result = await repository.LoadAsync();
        await Assert.That(result.IsSuccess).IsTrue();
        await Assert.That(result.Value.PublicSymbols).Contains("SDL_Init");
        await Assert.That(result.Value.PublicSymbols).Contains("SDL_Quit");
        await Assert.That(result.Value.PublicSymbols.Count).IsEqualTo(2);
        await Assert.That(result.Value.SourcePath).IsEqualTo("/repo/external/vcpkg/buildtrees/sdl2/src/one/src/dynapi/SDL2.exports");
        await Assert.That(result.Value.Origin).IsEqualTo(DynapiManifestOrigin.VcpkgBuildtree);
    }

    [Test]
    public async Task LoadAsync_Should_Return_NotFound_When_No_File_Matches()
    {
        var world = FakeCakeWorld.CreateLinux();
        var repository = new DynapiManifestRepository(world.CakeContext, world.CreateBuildContext().Paths);
        var result = await repository.LoadAsync();
        await Assert.That(result.IsFailure).IsTrue();
        await Assert.That(result.Error.Reason).IsEqualTo(
            "SDL2 dynapi manifest not found under '/repo/external/vcpkg/buildtrees/sdl2/src/*/src/dynapi/SDL2.exports'. " +
            "The binding-generator container bakes vcpkg state at image build time; CI's vcpkg-setup action caches buildtrees/sdl2/src alongside the binary cache. " +
            "On a host dev machine the path is populated by any vcpkg install sdl2 flow (tools.cs setup or direct vcpkg invocation).");
    }

    [Test]
    public async Task LoadAsync_Should_Return_AmbiguousGlobMatches_When_Two_Files_Match()
    {
        var world = FakeCakeWorld.CreateLinux()
            .WithTextFile("external/vcpkg/buildtrees/sdl2/src/z/src/dynapi/SDL2.exports", "++'_SDL_Quit'.'SDL2.dll'.'SDL_Quit'")
            .WithTextFile("external/vcpkg/buildtrees/sdl2/src/a/src/dynapi/SDL2.exports", "++'_SDL_Init'.'SDL2.dll'.'SDL_Init'");
        var repository = new DynapiManifestRepository(world.CakeContext, world.CreateBuildContext().Paths);
        var result = await repository.LoadAsync();
        await Assert.That(result.IsFailure).IsTrue();
        await Assert.That(result.Error.Reason).IsEqualTo(
            "SDL2 dynapi manifest glob '/repo/external/vcpkg/buildtrees/sdl2/src/*/src/dynapi/SDL2.exports' matched multiple candidates: " +
            "'/repo/external/vcpkg/buildtrees/sdl2/src/a/src/dynapi/SDL2.exports', '/repo/external/vcpkg/buildtrees/sdl2/src/z/src/dynapi/SDL2.exports'. " +
            "This usually means a stale buildtree from a previous vcpkg pin was left on disk after a version downgrade. " +
            "Delete the unwanted directory under external/vcpkg/buildtrees/sdl2/src/ before re-running.");
    }

    [Test]
    public async Task LoadAsync_Should_Return_ParseFailure_When_Export_Line_Is_Malformed()
    {
        var world = FakeCakeWorld.CreateLinux().WithTextFile(
            "external/vcpkg/buildtrees/sdl2/src/one/src/dynapi/SDL2.exports", "# comment\n++ malformed line");
        var repository = new DynapiManifestRepository(world.CakeContext, world.CreateBuildContext().Paths);
        var result = await repository.LoadAsync();
        await Assert.That(result.IsFailure).IsTrue();
        await Assert.That(result.Error.Reason).IsEqualTo(
            "SDL2 dynapi manifest at '/repo/external/vcpkg/buildtrees/sdl2/src/one/src/dynapi/SDL2.exports' failed to parse: " +
            "Dynapi manifest '/repo/external/vcpkg/buildtrees/sdl2/src/one/src/dynapi/SDL2.exports' line 2: " +
            "export line did not match the canonical Watcom format: '++ malformed line'.");
    }

    [Test]
    public async Task Parse_Should_Return_Active_Exports()
    {
        const string content = """
# Windows exports file for Watcom
# DO NOT EDIT THIS FILE BY HAND. It is autogenerated by gendynapi.pl.
++'_SDL_Init'.'SDL2.dll'.'SDL_Init'
++'_SDL_Quit'.'SDL2.dll'.'SDL_Quit'
++'_SDL_GetError'.'SDL2.dll'.'SDL_GetError'
""";

        var manifest = DynapiManifestRepository.Parse(content, _samplePath);

        await Assert.That(manifest.PublicSymbols).IsEquivalentTo(ThreeSymbolsExpected);
        await Assert.That(manifest.Origin).IsEqualTo(DynapiManifestOrigin.VcpkgBuildtree);
        await Assert.That(manifest.SourcePath).IsEqualTo(_samplePath);
    }

    [Test]
    public async Task Parse_Should_Include_Watcom_Disabled_Active_Exports()
    {
        // Lines prefixed with '# ' that still carry the canonical '++'_NAME'.'SDL2.dll'.'NAME''
        // shape are exports the SDL2 Watcom DEF-file build skips. The modern SDL2
        // dynamic library on Linux / macOS / Windows still ships these symbols
        // (SDL_dynapi_procs.h enumerates them as real function-pointer entries) —
        // only the legacy Watcom build path disables them. They must land in
        // PublicSymbols so the binding generator's validator does not flag the
        // emitted P/Invokes as false positives.
        const string content = """
++'_SDL_Init'.'SDL2.dll'.'SDL_Init'
# ++'_SDL_iPhoneSetAnimationCallback'.'SDL2.dll'.'SDL_iPhoneSetAnimationCallback'
# ++'_SDL_WinRTRunApp'.'SDL2.dll'.'SDL_WinRTRunApp'
++'_SDL_Quit'.'SDL2.dll'.'SDL_Quit'
""";

        var manifest = DynapiManifestRepository.Parse(content, _samplePath);

        await Assert.That(manifest.PublicSymbols).Contains("SDL_Init");
        await Assert.That(manifest.PublicSymbols).Contains("SDL_Quit");
        await Assert.That(manifest.PublicSymbols).Contains("SDL_iPhoneSetAnimationCallback");
        await Assert.That(manifest.PublicSymbols).Contains("SDL_WinRTRunApp");
        await Assert.That(manifest.PublicSymbols.Count).IsEqualTo(4);
    }

    [Test]
    public async Task Parse_Should_Skip_Pure_Comment_Lines_Without_Export_Marker()
    {
        const string content = """
# Windows exports file for Watcom
# DO NOT EDIT THIS FILE BY HAND. It is autogenerated by gendynapi.pl.
++'_SDL_Init'.'SDL2.dll'.'SDL_Init'
""";

        var manifest = DynapiManifestRepository.Parse(content, _samplePath);

        await Assert.That(manifest.PublicSymbols).IsEquivalentTo(OneSymbolExpected);
    }

    [Test]
    public async Task Parse_Should_Skip_Blank_Lines_And_Bom_Variants()
    {
        const string content = "\r\n++'_SDL_Init'.'SDL2.dll'.'SDL_Init'\r\n\r\n";

        var manifest = DynapiManifestRepository.Parse(content, _samplePath);

        await Assert.That(manifest.PublicSymbols).IsEquivalentTo(OneSymbolExpected);
    }

    [Test]
    public async Task Parse_Should_Return_Empty_Manifest_For_Comment_Only_Input()
    {
        const string content = """
# Header line one
# Header line two
""";

        var manifest = DynapiManifestRepository.Parse(content, _samplePath);

        await Assert.That(manifest.PublicSymbols).IsEmpty();
    }

    [Test]
    public async Task Parse_Should_Throw_When_Active_Line_Does_Not_Match_Watcom_Format()
    {
        const string content = "++ malformed line";

        var ex = Assert.Throws<InvalidOperationException>(
            () => DynapiManifestRepository.Parse(content, _samplePath));

        await Assert.That(ex.Message).Contains("export line did not match");
    }

    [Test]
    public async Task Parse_Should_Throw_When_Watcom_Disabled_Line_Is_Malformed()
    {
        const string content = "# ++ malformed line";

        var ex = Assert.Throws<InvalidOperationException>(
            () => DynapiManifestRepository.Parse(content, _samplePath));

        await Assert.That(ex.Message).Contains("export line did not match");
    }

    [Test]
    public async Task Parse_Should_Throw_When_Underscore_Prefix_And_Mirror_Disagree()
    {
        const string content = "++'_SDL_Init'.'SDL2.dll'.'SDL_Something'";

        var ex = Assert.Throws<InvalidOperationException>(
            () => DynapiManifestRepository.Parse(content, _samplePath));

        await Assert.That(ex.Message).Contains("symbol mismatch");
    }

    [Test]
    public async Task Parse_Should_Throw_When_Non_Comment_Non_Export_Line_Present()
    {
        const string content = "some unexpected text line";

        var ex = Assert.Throws<InvalidOperationException>(
            () => DynapiManifestRepository.Parse(content, _samplePath));

        await Assert.That(ex.Message).Contains("unexpected non-comment, non-export line");
    }
}
