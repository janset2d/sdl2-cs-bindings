using Build.Targets.GenerateBindings.PostProcess;
using Build.Tests.Fixtures;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Build.Tests.Unit.Targets.GenerateBindings.PostProcess;

public sealed class PublicTypedMethodProjectionTests
{
    [Test]
    public async Task BuildPublicClassContent_Should_Project_Types_Attributes_Callbacks_Constants_And_Order()
    {
        var source = PostProcessFixture.Source("raw");
        var output = GeneratedSyntaxFiles.NormalizeLineEndings(PostProcessFixture.Project(source));

        foreach (var expected in PostProcessFixture.Lines("publicContains"))
        {
            await Assert.That(output).Contains(expected);
        }

        foreach (var unexpected in PostProcessFixture.Lines("publicNotContains"))
        {
            await Assert.That(output).DoesNotContain(unexpected);
        }

        var options = CSharpParseOptions.Default.WithPreprocessorSymbols("NET5_0_OR_GREATER", "NET6_0_OR_GREATER");
        var root = await CSharpSyntaxTree.ParseText(output, options).GetRootAsync();
        var methods = root.DescendantNodes().OfType<MethodDeclarationSyntax>().ToArray();
        await Assert.That(methods.Single(method => method.Identifier.Text == "SDL_SetEventFilter").ParameterList.ToString()).DoesNotContain("delegate*");
        await Assert.That(methods.Single(method => method.Identifier.Text == "SDL_GetEventFilter").ParameterList.ToString()).DoesNotContain("delegate*");
        var start = output.IndexOf("#else", output.IndexOf("SDL_GetDefaultAssertionHandler(", StringComparison.Ordinal), StringComparison.Ordinal);
        var end = output.IndexOf("#endif", start, StringComparison.Ordinal);
        await Assert.That(output[start..end]).DoesNotContain("delegate*");
        var alpha = output.IndexOf("SDL_ALPHA_OPAQUE", StringComparison.Ordinal);
        var hint = output.IndexOf("SDL_HINT_RENDER_SCALE_QUALITY", StringComparison.Ordinal);
        var apple = output.IndexOf("SDL_Apple", StringComparison.Ordinal);
        var zebra = output.IndexOf("SDL_Zebra", StringComparison.Ordinal);
        await Assert.That(alpha).IsGreaterThanOrEqualTo(0);
        await Assert.That(hint).IsGreaterThan(alpha);
        await Assert.That(apple).IsGreaterThan(hint);
        await Assert.That(zebra).IsGreaterThan(apple);
        await Assert.That(string.Join(',', methods.Where(method => method.Identifier.Text is "SDL_Apple" or "SDL_Zebra").Select(method => method.Identifier.Text)))
            .IsEqualTo("SDL_Apple,SDL_Zebra");
        var empty = PostProcessFixture.Project(PostProcessFixture.Source("emptyRaw"));
        await Assert.That(empty).Contains("public static unsafe partial class SDL");
        var satellite = PostProcessFixture.Source("satelliteRaw");
        var satellitePublic = PostProcessFixture.Project(satellite, "SDL_image", "SDL_imageNative", "SDL2.Image");
        await Assert.That(satellitePublic).Contains("IMG_UpdateTexture(SDL_Renderer renderer, SDL_Surface* surface) => SDL_imageNative.IMG_UpdateTexture(renderer, surface);");
        await Assert.That(satellitePublic).DoesNotContain("using SDL2;");
        var coreTypes = PostProcessFixture.Source("coreTypes");
        await Assert.That(PostProcessFixture.CompilationErrors(coreTypes + "\n// <auto-generated-split />\n" + satellite + "\n" + satellitePublic, true)).IsEmpty();
    }

    [Test]
    public async Task BuildPublicClassContent_Should_Compile_With_Modern_And_Compat_Raw_Stubs()
    {
        var modern = PostProcessFixture.Source("publicModern");
        var publicText = PostProcessFixture.Project(modern);
        await Assert.That(publicText).Contains("public static long TTF_FontFaces(TTF_Font font)");
        await Assert.That(PostProcessFixture.CompilationErrors(modern + "\n" + publicText, true)).IsEmpty();
        await Assert.That(PostProcessFixture.CompilationErrors(PostProcessFixture.Source("publicCompat") + "\n" + publicText, false)).IsEmpty();
    }
}
