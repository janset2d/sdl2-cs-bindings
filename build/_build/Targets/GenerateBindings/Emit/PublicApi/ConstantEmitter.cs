using System.Text;
using Build.Targets.GenerateBindings.Emit;
using Build.Host.Text;
using Build.Targets.GenerateBindings.Model;

namespace Build.Targets.GenerateBindings.Emit.PublicApi;

internal static class ConstantEmitter
{
    public static GeneratedFile Emit(IReadOnlyList<BindingConstant> constants, BindingEmissionOptions options)
    {
        ArgumentNullException.ThrowIfNull(constants);
        ArgumentNullException.ThrowIfNull(options);

        return new GeneratedFile("Constants.g.cs", EmitConstantsFile(constants, options));
    }

    private static string EmitConstantsFile(IReadOnlyList<BindingConstant> constants, BindingEmissionOptions options)
    {
        var builder = new StringBuilder();
        builder.AppendLf("// <auto-generated />");
        builder.AppendLf();
        if (constants.Any(IsUtf8SpanConstant))
        {
            builder.AppendLf("using System;");
            builder.AppendLf();
        }

        builder.Append("namespace ").Append(options.ManagedNamespace).AppendLf(';');
        builder.AppendLf();
        builder.Append("public static partial class ").AppendLf(options.PrimaryClassName);
        builder.AppendLf('{');

        for (var i = 0; i < constants.Count; i++)
        {
            if (i > 0)
            {
                builder.AppendLf();
            }

            AppendConstant(builder, constants[i]);
        }

        builder.AppendLf('}');
        return builder.ToString();
    }

    private static void AppendConstant(StringBuilder builder, BindingConstant constant)
    {
        if (IsUtf8SpanConstant(constant))
        {
            builder
                .Append("    public static ")
                .Append(constant.Type.ManagedName)
                .Append(' ')
                .Append(constant.Name)
                .Append(" => ")
                .Append(constant.Value)
                .AppendLf(';');
            return;
        }

        builder
            .Append("    public const ")
            .Append(constant.Type.ManagedName)
            .Append(' ')
            .Append(constant.Name)
            .Append(" = ")
            .Append(constant.Value)
            .AppendLf(';');
    }

    private static bool IsUtf8SpanConstant(BindingConstant constant) =>
        string.Equals(constant.Type.ManagedName, "ReadOnlySpan<byte>", StringComparison.Ordinal);
}
