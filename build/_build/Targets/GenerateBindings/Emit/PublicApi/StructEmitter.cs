using System.Runtime.InteropServices;
using System.Text;
using Build.Targets.GenerateBindings.Emit;
using Build.Host.Text;
using Build.Targets.GenerateBindings.Model;

namespace Build.Targets.GenerateBindings.Emit.PublicApi;

internal static class StructEmitter
{
    public static GeneratedFile Emit(IReadOnlyList<BindingStruct> structs, BindingEmissionOptions options)
    {
        ArgumentNullException.ThrowIfNull(options);
        return new("Types/Structs.g.cs", EmitStructsFile(structs, options));
    }

    private static string EmitStructsFile(IReadOnlyList<BindingStruct> structs, BindingEmissionOptions options)
    {
        var wrapperArrays = CollectWrapperArrays(structs);

        var builder = new StringBuilder();
        builder.AppendLf("// <auto-generated />");
        builder.AppendLf();
        builder.AppendLf("using System.Runtime.InteropServices;");
        builder.AppendLf();
        builder.Append("namespace ").Append(options.ManagedNamespace).AppendLf(';');

        foreach (var structure in structs)
        {
            builder.AppendLf();
            AppendStruct(builder, structure);
        }

        foreach (var wrapperArray in wrapperArrays)
        {
            builder.AppendLf();
            AppendWrapperArray(builder, wrapperArray);
        }

        return builder.ToString();
    }

    private static void AppendStruct(StringBuilder builder, BindingStruct structure)
    {
        if (structure.Layout == LayoutKind.Explicit)
        {
            builder
                .Append("[StructLayout(LayoutKind.Explicit");
            if (structure.ExplicitSize is int explicitSize)
            {
                builder.Append(", Size = ").Append(explicitSize);
            }
            builder.AppendLf(")]");
        }
        else
        {
            builder.AppendLf("[StructLayout(LayoutKind.Sequential)]");
        }

        builder
            .Append("public ")
            .Append(RequiresUnsafe(structure) ? "unsafe " : string.Empty)
            .Append("partial struct ")
            .AppendLf(structure.Name);
        builder.AppendLf('{');

        for (var i = 0; i < structure.Fields.Count; i++)
        {
            var field = structure.Fields[i];
            if (i > 0)
            {
                builder.AppendLf();
            }

            AppendField(builder, structure, field);
        }

        builder.AppendLf('}');
    }

    private static void AppendField(StringBuilder builder, BindingStruct structure, BindingStructField field)
    {
        if (field.FieldOffset is int offset)
        {
            builder.Append("    [FieldOffset(").Append(offset).AppendLf(")]");
        }

        builder
            .Append("    public ");
        if (field.FixedBufferLength is int fixedBufferLength)
        {
            if (!FixedArrayEmissionPolicy.CanEmitFixedBuffer(field))
            {
                builder
                    .Append(CreateWrapperArrayName(structure.Name, field.Name))
                    .Append(' ')
                    .Append(field.Name)
                    .AppendLf(';');
                return;
            }

            builder
                .Append("fixed ")
                .Append(field.Type.ManagedName)
                .Append(' ')
                .Append(field.Name)
                .Append('[')
                .Append(fixedBufferLength)
                .AppendLf("];");
            return;
        }

        builder
            .Append(field.Type.ManagedName)
            .Append(' ')
            .Append(field.Name)
            .AppendLf(';');
    }

    private static bool RequiresUnsafe(BindingStruct structure) =>
        structure.Fields.Any(FieldRequiresUnsafe);

    private static bool FieldRequiresUnsafe(BindingStructField field) =>
        field.FixedBufferLength is null
            ? field.Type.PointerDepth > 0
            : FixedArrayEmissionPolicy.CanEmitFixedBuffer(field);

    private static List<WrapperArrayDeclaration> CollectWrapperArrays(IReadOnlyList<BindingStruct> structs)
    {
        var declarations = new Dictionary<string, WrapperArrayDeclaration>(StringComparer.Ordinal);
        foreach (var structure in structs)
        {
            foreach (var field in structure.Fields)
            {
                if (field.FixedBufferLength is not int length || FixedArrayEmissionPolicy.CanEmitFixedBuffer(field))
                {
                    continue;
                }

                var name = CreateWrapperArrayName(structure.Name, field.Name);
                var declaration = new WrapperArrayDeclaration(name, field.Type, length);
                if (declarations.TryGetValue(name, out var existing) && !existing.Equals(declaration))
                {
                    throw new InvalidOperationException(
                        $"Generated fixed-array wrapper name collision for '{name}'.");
                }

                declarations[name] = declaration;
            }
        }

        return declarations.Values.OrderBy(declaration => declaration.Name, StringComparer.Ordinal).ToList();
    }

    private static void AppendWrapperArray(StringBuilder builder, WrapperArrayDeclaration declaration)
    {
        builder.AppendLf("[StructLayout(LayoutKind.Sequential)]");
        builder
            .Append("public ")
            .Append(declaration.ElementType.PointerDepth > 0 ? "unsafe " : string.Empty)
            .Append("partial struct ")
            .AppendLf(declaration.Name);
        builder.AppendLf('{');

        for (var index = 0; index < declaration.Length; index++)
        {
            if (index > 0)
            {
                builder.AppendLf();
            }

            builder
                .Append("    public ")
                .Append(declaration.ElementType.ManagedName)
                .Append(" Element")
                .Append(index)
                .AppendLf(';');
        }

        builder.AppendLf('}');
    }

    private static string CreateWrapperArrayName(string parentStructName, string fieldName)
    {
        var segment = string.IsNullOrWhiteSpace(fieldName)
            ? "Array"
            : fieldName.TrimStart('@');
        return parentStructName + "_" + segment;
    }

    private sealed record WrapperArrayDeclaration(string Name, NativeTypeRef ElementType, int Length);
}
