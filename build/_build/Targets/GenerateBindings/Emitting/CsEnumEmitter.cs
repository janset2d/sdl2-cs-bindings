using System.Text;
using Build.Host.Text;
using Build.Targets.GenerateBindings.Model;

namespace Build.Targets.GenerateBindings.Emitting;

internal static class CsEnumEmitter
{
    public static GeneratedFile Emit(IReadOnlyList<BindingEnumeration> enumerations, BindingEmissionOptions options)
    {
        ArgumentNullException.ThrowIfNull(enumerations);
        ArgumentNullException.ThrowIfNull(options);

        return new GeneratedFile("Types/Enums.g.cs", EmitEnumsFile(enumerations, options));
    }

    private static string EmitEnumsFile(IReadOnlyList<BindingEnumeration> enumerations, BindingEmissionOptions options)
    {
        var builder = new StringBuilder();
        builder.AppendLf("// <auto-generated />");
        builder.AppendLf();
        if (enumerations.Any(enumeration => enumeration.IsFlags))
        {
            builder.AppendLf("using System;");
            builder.AppendLf();
        }

        builder.Append("namespace ").Append(options.ManagedNamespace).AppendLf(';');

        foreach (var enumeration in enumerations)
        {
            builder.AppendLf();
            AppendEnum(builder, enumeration);
        }

        return builder.ToString();
    }

    private static void AppendEnum(StringBuilder builder, BindingEnumeration enumeration)
    {
        if (enumeration.IsFlags)
        {
            builder.AppendLf("[Flags]");
        }

        builder
            .Append("public enum ")
            .Append(enumeration.Name)
            .Append(" : ")
            .AppendLf(enumeration.UnderlyingType.ManagedName);
        builder.AppendLf('{');

        foreach (var member in enumeration.Members)
        {
            builder
                .Append("    ")
                .Append(member.Name)
                .Append(" = ")
                .Append(member.Value)
                .AppendLf(',');
        }

        builder.AppendLf('}');
    }
}
