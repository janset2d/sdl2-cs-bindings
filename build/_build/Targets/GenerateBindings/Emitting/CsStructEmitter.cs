using System.Runtime.InteropServices;
using System.Text;
using Build.Host.Text;
using Build.Targets.GenerateBindings.Model;

namespace Build.Targets.GenerateBindings.Emitting;

internal static class CsStructEmitter
{
    private static readonly HashSet<string> FixedBufferElementTypes = new(StringComparer.Ordinal)
    {
        "bool",
        "byte",
        "short",
        "int",
        "long",
        "char",
        "sbyte",
        "ushort",
        "uint",
        "ulong",
        "float",
        "double",
    };

    public static GeneratedFile Emit(IReadOnlyList<BindingStruct> structs) =>
        new("Types/Structs.g.cs", EmitStructsFile(structs));

    private static string EmitStructsFile(IReadOnlyList<BindingStruct> structs)
    {
        var inlineArrays = CollectInlineArrays(structs);

        var builder = new StringBuilder();
        builder.AppendLf("// <auto-generated />");
        builder.AppendLf();
        if (inlineArrays.Count > 0)
        {
            builder.AppendLf("using System.Runtime.CompilerServices;");
        }
        builder.AppendLf("using System.Runtime.InteropServices;");
        builder.AppendLf();
        builder.AppendLf("namespace Janset.SDL2.Core;");

        foreach (var structure in structs)
        {
            builder.AppendLf();
            AppendStruct(builder, structure);
        }

        foreach (var inlineArray in inlineArrays)
        {
            builder.AppendLf();
            AppendInlineArray(builder, inlineArray);
        }

        return builder.ToString();
    }

    private static void AppendStruct(StringBuilder builder, BindingStruct structure)
    {
        if (structure.Layout == LayoutKind.Explicit)
        {
            builder
                .Append("[StructLayout(LayoutKind.Explicit");
            if (structure.ExplicitSize is int explicitSize)
            {
                builder.Append(", Size = ").Append(explicitSize);
            }
            builder.AppendLf(")]");
        }
        else
        {
            builder.AppendLf("[StructLayout(LayoutKind.Sequential)]");
        }

        builder
            .Append("public ")
            .Append(RequiresUnsafe(structure) ? "unsafe " : string.Empty)
            .Append("partial struct ")
            .AppendLf(structure.Name);
        builder.AppendLf('{');

        for (var i = 0; i < structure.Fields.Count; i++)
        {
            var field = structure.Fields[i];
            if (i > 0)
            {
                builder.AppendLf();
            }

            AppendField(builder, structure, field);
        }

        builder.AppendLf('}');
    }

    private static void AppendField(StringBuilder builder, BindingStruct structure, BindingStructField field)
    {
        if (field.FieldOffset is int offset)
        {
            builder.Append("    [FieldOffset(").Append(offset).AppendLf(")]");
        }

        builder
            .Append("    public ");
        if (field.FixedBufferLength is int fixedBufferLength)
        {
            if (!CanEmitFixedBuffer(field))
            {
                builder
                    .Append(CreateInlineArrayName(structure.Name, field.Name))
                    .Append(' ')
                    .Append(field.Name)
                    .AppendLf(';');
                return;
            }

            builder
                .Append("fixed ")
                .Append(field.Type.ManagedName)
                .Append(' ')
                .Append(field.Name)
                .Append('[')
                .Append(fixedBufferLength)
                .AppendLf("];");
            return;
        }

        builder
            .Append(field.Type.ManagedName)
            .Append(' ')
            .Append(field.Name)
            .AppendLf(';');
    }

    private static bool RequiresUnsafe(BindingStruct structure) =>
        structure.Fields.Any(field => field.Type.IsPointer || (field.FixedBufferLength is not null && CanEmitFixedBuffer(field)));

    private static List<InlineArrayDeclaration> CollectInlineArrays(IReadOnlyList<BindingStruct> structs)
    {
        var declarations = new Dictionary<string, InlineArrayDeclaration>(StringComparer.Ordinal);
        foreach (var structure in structs)
        {
            foreach (var field in structure.Fields)
            {
                if (field.FixedBufferLength is not int length || CanEmitFixedBuffer(field))
                {
                    continue;
                }

                var name = CreateInlineArrayName(structure.Name, field.Name);
                var declaration = new InlineArrayDeclaration(name, field.Type, length);
                if (declarations.TryGetValue(name, out var existing) && !existing.Equals(declaration))
                {
                    throw new InvalidOperationException(
                        $"Generated inline array name collision for '{name}'.");
                }

                declarations[name] = declaration;
            }
        }

        return declarations.Values.OrderBy(declaration => declaration.Name, StringComparer.Ordinal).ToList();
    }

    private static void AppendInlineArray(StringBuilder builder, InlineArrayDeclaration declaration)
    {
        builder.Append("[InlineArray(").Append(declaration.Length).AppendLf(")]");
        builder
            .Append("public ")
            .Append(declaration.ElementType.IsPointer ? "unsafe " : string.Empty)
            .Append("partial struct ")
            .AppendLf(declaration.Name);
        builder.AppendLf('{');
        builder
            .Append("    private ")
            .Append(declaration.ElementType.ManagedName)
            .AppendLf(" _element0;");
        builder.AppendLf('}');
    }

    private static bool CanEmitFixedBuffer(BindingStructField field) =>
        FixedBufferElementTypes.Contains(field.Type.ManagedName);

    private static string CreateInlineArrayName(string parentStructName, string fieldName)
    {
        var segment = string.IsNullOrWhiteSpace(fieldName)
            ? "Array"
            : fieldName.TrimStart('@');
        return parentStructName + "_" + segment;
    }

    private sealed record InlineArrayDeclaration(string Name, BindingTypeRef ElementType, int Length);
}
