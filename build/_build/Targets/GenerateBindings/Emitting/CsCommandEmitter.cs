using System.Text;
using System.Text.Json;
using Build.Host.Text;
using Build.Targets.GenerateBindings.Model;

namespace Build.Targets.GenerateBindings.Emitting;

internal static class CsCommandEmitter
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
    };

    public static GeneratedFileSet Emit(BindingModel model, BindingEmissionOptions options)
    {
        ArgumentNullException.ThrowIfNull(model);
        ArgumentNullException.ThrowIfNull(options);

        var files = new List<GeneratedFile>();

        var libNameViewIndex = FindLibNameViewIndex(model.Views);
        for (var index = 0; index < model.Views.Count; index++)
        {
            var view = model.Views[index];
            files.Add(new GeneratedFile(RelativePath: $"Platform/{view.Name}/Commands.g.cs", Content: EmitCommandsFile(view, options, includeLibName: index == libNameViewIndex)));
        }

        if (model.Structs.Count > 0)
        {
            files.Add(CsStructEmitter.Emit(model.Structs, options));
        }

        if (model.Enums.Count > 0)
        {
            files.Add(CsEnumEmitter.Emit(model.Enums, options));
        }

        if (model.Constants.Count > 0)
        {
            files.Add(CsConstantEmitter.Emit(model.Constants, options));
        }

        files.Add(new GeneratedFile(RelativePath: "parse-views.json", Content: EmitReportJson(model)));

        return new GeneratedFileSet(files);
    }

    private static int FindLibNameViewIndex(IReadOnlyList<BindingParseView> views)
    {
        for (var index = 0; index < views.Count; index++)
        {
            if (string.Equals(views[index].Name, "Neutral", StringComparison.Ordinal))
            {
                return index;
            }
        }

        return 0;
    }

    private static string EmitCommandsFile(BindingParseView view, BindingEmissionOptions options, bool includeLibName)
    {
        // AppendLf (Host.Text) forces '\n' regardless of host OS so generated
        // .g.cs content stays byte-identical across Windows dev / Linux container
        // / CI runner. System.Text.Json's indented serializer in .NET 7+ already
        // defaults to "\n" so the JSON sidecar inherits the same convention.
        var builder = new StringBuilder();
        builder.AppendLf("// <auto-generated />");
        builder.Append("// Parse view: ").AppendLf(view.Name);
        builder.AppendLf();
        builder.AppendLf("using System;");
        builder.AppendLf("using System.Runtime.InteropServices;");
        if (view.SupportedOsPlatform is not null)
        {
            builder.AppendLf("using System.Runtime.Versioning;");
        }

        builder.AppendLf();
        builder.Append("namespace ").Append(options.ManagedNamespace).AppendLf(';');
        builder.AppendLf();
        builder.Append("internal static unsafe partial class ").AppendLf(options.RawClassName);
        builder.AppendLf('{');
        if (includeLibName)
        {
            builder.AppendLf("    private const string LibName = \"SDL2\";");
        }

        foreach (var function in view.Functions)
        {
            builder.AppendLf();
            if (view.SupportedOsPlatform is not null)
            {
                builder.Append("    [SupportedOSPlatform(\"").Append(view.SupportedOsPlatform).AppendLf("\")]");
            }

            builder.AppendLf("    [DefaultDllImportSearchPaths(DllImportSearchPath.SafeDirectories)]");
            builder.AppendLf("    [DllImport(LibName, CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]");
            builder
                .Append("    internal static extern ")
                .Append(function.ReturnType.ManagedName)
                .Append(' ')
                .Append(function.Name)
                .Append('(')
                .Append(JoinParameters(function.Parameters))
                .AppendLf(");");
        }

        builder.AppendLf('}');
        return builder.ToString();
    }

    private static string JoinParameters(IReadOnlyList<BindingParameter> parameters)
    {
        return string.Join(", ", parameters.Select(p => $"{p.Type.ManagedName} {p.Name}"));
    }

    private static string EmitReportJson(BindingModel model)
    {
        var entries = model.Views.Select(view =>
            new BindingParseViewReportEntry(
                Name: view.Name,
                SupportedOSPlatform: view.SupportedOsPlatform,
                FunctionCount: view.Functions.Count,
                Functions: [.. view.Functions.Select(f => new BindingParseViewReportFunction(f.Name, f.SourceHeader))])).ToList();

        var report = new BindingParseViewReport(entries);
        return JsonSerializer.Serialize(report, JsonOptions);
    }
}
