using System.Text;
using Build.Host.Text;
using Build.Targets.GenerateBindings.Model;

namespace Build.Targets.GenerateBindings.Emitting;

internal static class CsCallbackEmitter
{
    public static GeneratedFile Emit(IReadOnlyList<BindingCallback> callbacks, BindingEmissionOptions options)
    {
        ArgumentNullException.ThrowIfNull(callbacks);
        ArgumentNullException.ThrowIfNull(options);

        var builder = new StringBuilder();
        builder.AppendLf("// <auto-generated />");
        builder.AppendLf();
        builder.AppendLf("using System.Runtime.InteropServices;");
        builder.AppendLf();
        builder.Append("namespace ").Append(options.ManagedNamespace).AppendLf(';');

        foreach (var callback in callbacks)
        {
            builder.AppendLf();
            AppendCallback(builder, callback);
        }

        return new GeneratedFile("Types/Callbacks.g.cs", builder.ToString());
    }

    private static void AppendCallback(StringBuilder builder, BindingCallback callback)
    {
        var usesModernCInteger = ModernCIntegerEmissionPolicy.UsesModernCInteger(callback);
        if (usesModernCInteger)
        {
            builder.Append("#if ").AppendLf(ModernCIntegerEmissionPolicy.Guard);
        }

        builder.AppendLf("[UnmanagedFunctionPointer(CallingConvention.Cdecl)]");
        builder
            .Append("public unsafe delegate ")
            .Append(callback.ReturnType.ManagedName)
            .Append(' ')
            .Append(callback.Name)
            .Append('(')
            .Append(JoinParameters(callback.Parameters))
            .AppendLf(");");

        if (usesModernCInteger)
        {
            builder.AppendLf("#endif");
        }
    }

    private static string JoinParameters(IReadOnlyList<BindingParameter> parameters)
    {
        return string.Join(", ", parameters.Select(parameter => $"{parameter.Type.ManagedName} {parameter.Name}"));
    }
}
