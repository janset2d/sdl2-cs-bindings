using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Janset.SDL2.PostProcess;

internal static class PublicTypedMethodProjection
{
    private static readonly HashSet<string> SuppressedConstNames = new(StringComparer.Ordinal)
    {
        "SDL_BYTEORDER",
        "SDL_FLOATWORDORDER",
    };

    public sealed record DiscoveredMembers(
        IReadOnlyList<ConstMember> Constants,
        IReadOnlyList<PropertyDeclarationSyntax> Properties,
        IReadOnlyList<MethodDeclarationSyntax> Methods);

    public sealed record ConstMember(
        string Name,
        string Type,
        string Value,
        SyntaxList<AttributeListSyntax> AttributeLists);

    public static DiscoveredMembers Discover(string inputDir, string rawClass)
    {
        var constants = new List<ConstMember>();
        var properties = new List<PropertyDeclarationSyntax>();
        var methods = new List<MethodDeclarationSyntax>();

        foreach (var file in Directory.EnumerateFiles(inputDir, "*.g.cs", SearchOption.AllDirectories).OrderBy(p => p, StringComparer.Ordinal))
        {
            var discovered = DiscoverFromSource(File.ReadAllText(file), rawClass);
            constants.AddRange(discovered.Constants);
            properties.AddRange(discovered.Properties);
            methods.AddRange(discovered.Methods);
        }

        return new DiscoveredMembers(constants, properties, methods);
    }

    public static DiscoveredMembers DiscoverFromSource(string source, string rawClass)
    {
        var root = CSharpSyntaxTree.ParseText(source).GetCompilationUnitRoot();
        var constants = new List<ConstMember>();
        var properties = new List<PropertyDeclarationSyntax>();
        var methods = new List<MethodDeclarationSyntax>();

        foreach (var raw in root.DescendantNodes().OfType<ClassDeclarationSyntax>()
            .Where(c => string.Equals(c.Identifier.ValueText, rawClass, StringComparison.Ordinal)))
        {
            foreach (var member in raw.Members)
            {
                switch (member)
                {
                    case MethodDeclarationSyntax method when IsPublic(method.Modifiers):
                        methods.Add(method);
                        break;
                    case FieldDeclarationSyntax field when IsPublicConst(field):
                        foreach (var variable in field.Declaration.Variables)
                        {
                            if (variable.Initializer is null)
                            {
                                continue;
                            }

                            constants.Add(new ConstMember(
                                variable.Identifier.ValueText,
                                field.Declaration.Type.ToString(),
                                variable.Initializer.Value.ToString(),
                                field.AttributeLists));
                        }
                        break;
                    case PropertyDeclarationSyntax property when IsPublicStringLikeMacroProperty(property):
                        properties.Add(property);
                        break;
                }
            }
        }

        return new DiscoveredMembers(constants, properties, methods);
    }

    public static string BuildPublicClassContent(
        DiscoveredMembers members,
        string publicClass,
        string rawClass,
        string namespaceName,
        HashSet<string> clongMethods)
    {
        var orderedConstants = members.Constants
            .Where(c => !IsSuppressedConst(c.Name))
            .OrderBy(c => c.Name, StringComparer.Ordinal)
            .ToArray();
        var orderedProperties = members.Properties
            .Where(p => !IsSuppressedConst(p.Identifier.ValueText))
            .OrderBy(p => p.Identifier.ValueText, StringComparer.Ordinal)
            .ToArray();
        var orderedMethods = members.Methods
            .OrderBy(m => m.Identifier.ValueText, StringComparer.Ordinal)
            .ThenBy(BuildSignatureSortKey, StringComparer.Ordinal)
            .ToArray();

        var needsPlatformUsing = orderedMethods.Any(HasPlatformAttribute) || orderedConstants.Any(c => HasPlatformAttribute(c.AttributeLists)) || orderedProperties.Any(HasPlatformAttribute);
        var needsSignedRangeHelper = false;
        var needsUnsignedRangeHelper = false;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.InteropServices;");
        if (needsPlatformUsing)
        {
            sb.AppendLine("#if NET5_0_OR_GREATER");
            sb.AppendLine("using System.Runtime.Versioning;");
            sb.AppendLine("#endif");
        }
        sb.AppendLine();
        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();
        sb.AppendLine($"public static unsafe partial class {publicClass}");
        sb.AppendLine("{");

        foreach (var constant in orderedConstants)
        {
            AppendAttributeLists(sb, constant.AttributeLists, "    ");
            sb.AppendLine($"    public const {constant.Type} {constant.Name} = {constant.Value};");
        }

        foreach (var property in orderedProperties)
        {
            AppendAttributeLists(sb, property.AttributeLists, "    ");
            sb.AppendLine($"    public static {property.Type} {property.Identifier.ValueText} => {property.ExpressionBody?.Expression.ToString()};");
        }

        foreach (var method in orderedMethods)
        {
            var model = BuildMethodModel(method, rawClass, clongMethods.Contains(method.Identifier.ValueText));
            needsSignedRangeHelper |= model.NeedsSignedRangeHelper;
            needsUnsignedRangeHelper |= model.NeedsUnsignedRangeHelper;
            AppendMethod(sb, model);
        }

        if (needsSignedRangeHelper || needsUnsignedRangeHelper)
        {
            if (orderedConstants.Length > 0 || orderedProperties.Length > 0 || orderedMethods.Length > 0)
            {
                sb.AppendLine();
            }
        }

        if (needsSignedRangeHelper)
        {
            sb.AppendLine("    private static void ThrowIfWindowsOutOfRange(long value)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (!RuntimeInformation.IsOSPlatform(OSPlatform.Windows))");
            sb.AppendLine("        {");
            sb.AppendLine("            return;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        if (value < int.MinValue || value > int.MaxValue)");
            sb.AppendLine("        {");
            sb.AppendLine("            throw new ArgumentOutOfRangeException(nameof(value));");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }

        if (needsUnsignedRangeHelper)
        {
            if (needsSignedRangeHelper)
            {
                sb.AppendLine();
            }

            sb.AppendLine("    private static void ThrowIfWindowsOutOfRange(ulong value)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (!RuntimeInformation.IsOSPlatform(OSPlatform.Windows))");
            sb.AppendLine("        {");
            sb.AppendLine("            return;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        if (value > uint.MaxValue)");
            sb.AppendLine("        {");
            sb.AppendLine("            throw new ArgumentOutOfRangeException(nameof(value));");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static MethodModel BuildMethodModel(MethodDeclarationSyntax method, string rawClass, bool isClongMethod)
    {
        var parameters = method.ParameterList.Parameters.Select(p => BuildParameterModel(p, isClongMethod)).ToArray();
        var returnType = BuildPublicType(method.ReturnType, isClongMethod, isReturn: true);
        var originalReturnType = method.ReturnType.ToString();
        var hasCallback = IsFunctionPointer(method.ReturnType) || parameters.Any(p => p.IsCallback);
        var needsBranch = isClongMethod || hasCallback;

        return new MethodModel(
            method.Identifier.ValueText,
            returnType.PublicType,
            originalReturnType,
            rawClass,
            method.AttributeLists,
            parameters,
            needsBranch,
            IsVoid: method.ReturnType is PredefinedTypeSyntax predefined && predefined.Keyword.IsKind(SyntaxKind.VoidKeyword),
            returnType.IsCallback,
            returnType.IsSignedClong,
            returnType.IsUnsignedClong,
            parameters.Any(p => p.IsSignedClong),
            parameters.Any(p => p.IsUnsignedClong));
    }

    private static ParameterModel BuildParameterModel(ParameterSyntax parameter, bool isClongMethod)
    {
        var type = parameter.Type ?? SyntaxFactory.ParseTypeName("object");
        var publicType = BuildPublicType(type, isClongMethod, isReturn: false);
        return new ParameterModel(
            parameter.Identifier.ValueText,
            publicType.PublicType,
            type.ToString(),
            parameter.AttributeLists,
            publicType.IsCallback,
            publicType.IsSignedClong,
            publicType.IsUnsignedClong);
    }

    private static TypeProjection BuildPublicType(TypeSyntax type, bool isClongMethod, bool isReturn)
    {
        if (IsFunctionPointer(type))
        {
            return new TypeProjection("nint", IsCallback: true, IsSignedClong: false, IsUnsignedClong: false);
        }

        if (type is PointerTypeSyntax { ElementType: FunctionPointerTypeSyntax })
        {
            return new TypeProjection("nint*", IsCallback: true, IsSignedClong: false, IsUnsignedClong: false);
        }

        if (isClongMethod && type.ToString() == "CLong")
        {
            return new TypeProjection("long", IsCallback: false, IsSignedClong: true, IsUnsignedClong: false);
        }

        if (isClongMethod && type.ToString() == "CULong")
        {
            return new TypeProjection("ulong", IsCallback: false, IsSignedClong: false, IsUnsignedClong: true);
        }

        return new TypeProjection(type.ToString(), IsCallback: false, IsSignedClong: false, IsUnsignedClong: false);
    }

    private static void AppendMethod(StringBuilder sb, MethodModel model)
    {
        if (sb.Length > 0 && !sb.ToString().EndsWith("{\n", StringComparison.Ordinal))
        {
            sb.AppendLine();
        }

        AppendAttributeLists(sb, model.AttributeLists, "    ");
        var parameterList = string.Join(", ", model.Parameters.Select(p => $"{RenderAttributeListsInline(p.AttributeLists)}{p.PublicType} {p.Name}"));

        if (!model.NeedsBranch)
        {
            var args = string.Join(", ", model.Parameters.Select(p => p.Name));
            sb.AppendLine($"    public static {model.PublicReturnType} {model.Name}({parameterList}) => {model.RawClass}.{model.Name}({args});");
            return;
        }

        sb.AppendLine($"    public static {model.PublicReturnType} {model.Name}({parameterList})");
        sb.AppendLine("    {");
        foreach (var parameter in model.Parameters.Where(p => p.IsSignedClong || p.IsUnsignedClong))
        {
            sb.AppendLine($"        ThrowIfWindowsOutOfRange({parameter.Name});");
        }

        sb.AppendLine("#if NET6_0_OR_GREATER");
        AppendCallStatement(sb, model, BuildModernArgumentList(model), modern: true);
        sb.AppendLine("#else");
        AppendCallStatement(sb, model, string.Join(", ", model.Parameters.Select(p => p.Name)), modern: false);
        sb.AppendLine("#endif");
        sb.AppendLine("    }");
    }

    private static void AppendCallStatement(StringBuilder sb, MethodModel model, string args, bool modern)
    {
        var call = $"{model.RawClass}.{model.Name}({args})";
        if (model.IsVoid)
        {
            sb.AppendLine($"        {call};");
            return;
        }

        if (modern && model.ReturnIsCallback)
        {
            sb.AppendLine($"        return (nint){call};");
            return;
        }

        if (modern && model.ReturnIsSignedClong)
        {
            sb.AppendLine($"        return (long){call}.Value;");
            return;
        }

        if (modern && model.ReturnIsUnsignedClong)
        {
            sb.AppendLine($"        return (ulong){call}.Value;");
            return;
        }

        sb.AppendLine($"        return {call};");
    }

    private static string BuildModernArgumentList(MethodModel model)
        => string.Join(", ", model.Parameters.Select(p =>
        {
            if (p.IsSignedClong)
            {
                return $"new CLong((nint){p.Name})";
            }

            if (p.IsUnsignedClong)
            {
                return $"new CULong((nuint){p.Name})";
            }

            if (p.IsCallback)
            {
                return $"({p.OriginalType}){p.Name}";
            }

            return p.Name;
        }));

    private static void AppendAttributeLists(StringBuilder sb, SyntaxList<AttributeListSyntax> attributeLists, string indentation)
    {
        foreach (var list in FilterAttributeLists(attributeLists))
        {
            var text = list.ToFullString().TrimEnd('\r', '\n');
            foreach (var line in text.Split('\n'))
            {
                var trimmed = line.Trim();
                if (trimmed.StartsWith("#", StringComparison.Ordinal))
                {
                    sb.AppendLine(trimmed);
                }
                else
                {
                    sb.Append(indentation);
                    sb.AppendLine(trimmed);
                }
            }
        }
    }

    private static string RenderAttributeListsInline(SyntaxList<AttributeListSyntax> attributeLists)
    {
        var rendered = string.Concat(FilterAttributeLists(attributeLists).Select(a => a.ToFullString().Trim() + " "));
        return rendered;
    }

    private static IEnumerable<AttributeListSyntax> FilterAttributeLists(SyntaxList<AttributeListSyntax> attributeLists)
    {
        foreach (var list in attributeLists)
        {
            var attributes = list.Attributes.Where(a => !IsRawAbiAttribute(a)).ToArray();
            if (attributes.Length == 0)
            {
                continue;
            }

            yield return list.WithAttributes(SyntaxFactory.SeparatedList(attributes));
        }
    }

    private static bool IsRawAbiAttribute(AttributeSyntax attribute)
    {
        var name = attribute.Name.ToString();
        var simpleName = name.Split('.').Last();
        if (simpleName.EndsWith("Attribute", StringComparison.Ordinal))
        {
            simpleName = simpleName[..^"Attribute".Length];
        }

        return simpleName is "NativeTypeName" or "LibraryImport" or "DllImport" or "UnmanagedCallConv";
    }

    private static bool IsPublicConst(FieldDeclarationSyntax field)
        => IsPublic(field.Modifiers) && field.Modifiers.Any(SyntaxKind.ConstKeyword);

    private static bool IsPublicStringLikeMacroProperty(PropertyDeclarationSyntax property)
        => IsPublic(property.Modifiers) &&
           property.Modifiers.Any(SyntaxKind.StaticKeyword) &&
           property.Type.ToString() == "ReadOnlySpan<byte>" &&
           property.ExpressionBody?.Expression is LiteralExpressionSyntax literal &&
           literal.Token.Text.EndsWith("u8", StringComparison.Ordinal);

    private static bool IsPublic(SyntaxTokenList modifiers)
        => modifiers.Any(SyntaxKind.PublicKeyword);

    private static bool IsSuppressedConst(string name)
        => SuppressedConstNames.Contains(name) ||
           (name.StartsWith("AUDIO_", StringComparison.Ordinal) && name.EndsWith("SYS", StringComparison.Ordinal));

    private static bool IsFunctionPointer(TypeSyntax type)
        => type is FunctionPointerTypeSyntax;

    private static string BuildSignatureSortKey(MethodDeclarationSyntax method)
        => method.ParameterList.ToString();

    private static bool HasPlatformAttribute(MethodDeclarationSyntax method)
        => HasPlatformAttribute(method.AttributeLists) || method.ParameterList.Parameters.Any(p => HasPlatformAttribute(p.AttributeLists));

    private static bool HasPlatformAttribute(PropertyDeclarationSyntax property)
        => HasPlatformAttribute(property.AttributeLists);

    private static bool HasPlatformAttribute(SyntaxList<AttributeListSyntax> attributeLists)
        => attributeLists.Any(a =>
        {
            var text = a.ToFullString();
            return text.Contains("SupportedOSPlatform", StringComparison.Ordinal) ||
                   text.Contains("UnsupportedOSPlatform", StringComparison.Ordinal);
        });

    private sealed record TypeProjection(string PublicType, bool IsCallback, bool IsSignedClong, bool IsUnsignedClong);

    private sealed record ParameterModel(
        string Name,
        string PublicType,
        string OriginalType,
        SyntaxList<AttributeListSyntax> AttributeLists,
        bool IsCallback,
        bool IsSignedClong,
        bool IsUnsignedClong);

    private sealed record MethodModel(
        string Name,
        string PublicReturnType,
        string OriginalReturnType,
        string RawClass,
        SyntaxList<AttributeListSyntax> AttributeLists,
        IReadOnlyList<ParameterModel> Parameters,
        bool NeedsBranch,
        bool IsVoid,
        bool ReturnIsCallback,
        bool ReturnIsSignedClong,
        bool ReturnIsUnsignedClong,
        bool NeedsSignedRangeHelper,
        bool NeedsUnsignedRangeHelper);
}
